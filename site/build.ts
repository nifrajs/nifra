/**
 * Build the site for Cloudflare Pages. Output: site/dist/ - every page prerendered as a static file,
 * the content-hashed client bundle under /assets/*, and a `_worker.js` (the Nifra SSR worker) for the
 * rest. Deploy with `wrangler pages deploy dist`.
 *
 *   bun run site/build.ts
 */
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { mdxBunPlugin } from "@nifrajs/content/mdx"
import { buildClient, buildServer } from "@nifrajs/web/build"
import { routesUnder } from "../scripts/gen-sitemap"
import { writeFrameworksArtifact } from "./build-frameworks"
import { buildSiteIslands } from "./build-islands"
import { SECURITY_HEADERS } from "./shared/security-headers"

const dir = import.meta.dir
const dist = `${dir}/dist`
// The sitemap's page set, which `check:sitemap` holds equal to site/routes. Step (5) writes each page.
const pages = routesUnder(`${dir}/..`).map((route) => route.url)

// `.mdx` routes (e.g. /docs/content) compile to React components - Nifra dogfoods its own MDX support.
const mdx = mdxBunPlugin({ jsxImportSource: "react" })

rmSync(dist, { recursive: true, force: true })
mkdirSync(`${dist}/assets`, { recursive: true })

// (0) The /frameworks live demo: render the shared catalog through all five UI adapters → five HTML
// fragments + five real client hydration bundles (dist/assets/fw-*.client.js), and measure each bundle's
// gzip size. Runs BEFORE the React client/server builds because the /frameworks route imports the JSON
// artifact this writes (shared/data/frameworks-demo.json). Each framework is its own isolated Bun.build, so
// Solid's Babel plugin / Svelte's compiler don't leak onto the React/Preact .tsx - see build-frameworks.ts.
await writeFrameworksArtifact({ outDir: `${dist}/assets` })

// (1) Client bundle → dist/assets/* (served by Pages at /assets/*).
const client = await buildClient({
  routesDir: `${dir}/routes`,
  outDir: `${dist}/assets`,
  clientModule: "@nifrajs/web-react/client",
  conditions: ["bun", "browser"],
  define: { "process.env.NODE_ENV": '"production"' },
  plugins: [mdx],
})
await buildSiteIslands({ outDir: `${dist}/assets` })

// (2) SSR worker (edge conditions: workerd/edge-light) → a self-contained `_worker.js`.
const { worker } = await buildServer({
  routesDir: `${dir}/routes`,
  serverEntry: `${dir}/_worker.ts`,
  outDir: `${dir}/dist-server`,
  clientEntry: client.entry,
  plugins: [mdx],
  define: {
    "process.env.NODE_ENV": '"production"',
    NIFRA_SITE_PAGES: JSON.stringify(pages),
  },
})

// (3) Assemble the Pages output dir.
cpSync(worker, `${dist}/_worker.js`)
cpSync(`${dir}/public/favicon.png`, `${dist}/assets/favicon.png`)
cpSync(`${dir}/public/apple-touch-icon.png`, `${dist}/assets/apple-touch-icon.png`)
cpSync(`${dir}/public/logo-mark.png`, `${dist}/assets/logo-mark.png`)
cpSync(`${dir}/public/og.jpg`, `${dist}/assets/og.jpg`)
cpSync(`${dir}/public/background.png`, `${dist}/assets/background.png`)
cpSync(`${dir}/public/nifra-bot-avatar.png`, `${dist}/assets/nifra-bot-avatar.png`)
// Self-hosted typefaces (content-hashed; written by build-fonts.ts, referenced from shared/data/fonts.json).
cpSync(`${dir}/public/fonts`, `${dist}/assets/fonts`, { recursive: true })
cpSync(`${dir}/public/media`, `${dist}/assets/media`, { recursive: true })
// AI-readable docs (llmstxt.org): the index + the full single-file reference, served at the site root
// so an LLM can fetch /llms.txt and /llms-full.txt. Canonical source is the repo root (one per repo).
cpSync(`${dir}/../llms.txt`, `${dist}/llms.txt`)
cpSync(`${dir}/../llms-full.txt`, `${dist}/llms-full.txt`)
// The generated library API reference (every public export + signature + doc), served at /api-reference.md.
cpSync(`${dir}/../api-reference.md`, `${dist}/api-reference.md`)
// The verified-example corpus, served at /examples.json, and the type-signature corpus (the exact
// TypeScript of every @nifrajs/* export), served at /types.json.
cpSync(`${dir}/../packages/cli/docs/examples.json`, `${dist}/examples.json`)
cpSync(`${dir}/../packages/cli/docs/types.json`, `${dist}/types.json`)
// Crawler surface: robots.txt + the sitemap + the blog feed, served statically at the site root.
// All three are generated by `bun run gen:sitemap` from site/routes and site/shared/data/posts.ts.
cpSync(`${dir}/public/robots.txt`, `${dist}/robots.txt`)
cpSync(`${dir}/public/sitemap.xml`, `${dist}/sitemap.xml`)
cpSync(`${dir}/public/rss.xml`, `${dist}/rss.xml`)
rmSync(`${dir}/dist-server`, { recursive: true, force: true })

// (4) What Pages serves without the worker. `_routes.json` excludes the client bundle, the static
// files, and every page step (5) writes; a section of several pages goes by prefix, since Cloudflare
// caps the file at 100 rules. A worker answer under an excluded prefix needs a `_redirects` line.
const sections = new Set(
  pages
    .filter((path) => path.indexOf("/", 1) !== -1)
    .map((path) => path.slice(0, path.indexOf("/", 1))),
)
const pageRules = pages.flatMap((path) => {
  const section = path.indexOf("/", 1) === -1 ? path : path.slice(0, path.indexOf("/", 1))
  if (sections.has(section)) return path === section ? [path, `${path}/*`] : []
  return path === "/" ? ["/", "/_data.json"] : [path, `${path}/_data.json`]
})
const exclude = [
  "/assets/*",
  "/llms.txt",
  "/llms-full.txt",
  "/api-reference.md",
  "/examples.json",
  "/types.json",
  "/robots.txt",
  "/sitemap.xml",
  "/rss.xml",
  ...pageRules,
]
if (exclude.length + 1 > 100) throw new Error(`_routes.json would hold ${exclude.length + 1} rules`)
writeFileSync(
  `${dist}/_routes.json`,
  `${JSON.stringify({ version: 1, include: ["/*"], exclude }, null, 2)}\n`,
)
// The nano lane merged into islands; old links land on the page that replaced it.
writeFileSync(`${dist}/_redirects`, "/docs/nano /docs/islands 301\n")
const securityHeaders = Object.entries(SECURITY_HEADERS).map(
  ([name, value]) => `  ${name}: ${value}`,
)
writeFileSync(
  `${dist}/_headers`,
  [
    "/*",
    ...securityHeaders,
    // Content-hashed by build-fonts.ts, so a cached font is never stale. OFL.txt beside them is not.
    ...readdirSync(`${dir}/public/fonts`)
      .filter((file) => file.endsWith(".woff2"))
      .sort()
      .flatMap((file) => [
        `/assets/fonts/${file}`,
        "  Cache-Control: public, max-age=31536000, immutable",
      ]),
    "",
  ].join("\n"),
)

// (5) Render every page through the assembled worker and write it as a static file: a page that throws
// while rendering fails the build. A child process: this one already holds @nifrajs/core from the
// build, and the worker bundles its own.
const rendered = Bun.spawnSync(
  [process.execPath, `${dir}/../scripts/site-pages.ts`, `${dist}/_worker.js`, "--out", dist],
  {
    stdout: "inherit",
    stderr: "inherit",
  },
)
if (rendered.exitCode !== 0) process.exit(1)

console.log(
  `Cloudflare Pages output: site/dist (_worker.js + _routes.json + client ${client.entry})`,
)
