/**
 * The starter's `.nifra/types`, written with the scaffold so `import type { Route } from "./+types/index"`
 * resolves before any nifra command has run. From the first `nifra dev|build|check|types` on, the
 * generator in `@nifrajs/web/route-types` owns the directory; `route-types.test.ts` holds this text
 * byte-equal to what that generator writes for every scaffold that has routes.
 */

/** The starter's route files: `[name, kind, has a backend half]`. */
const STARTER_ROUTES = [
  ["_404", "page", false],
  ["_layout", "layout", false],
  ["index", "page", true],
] as const

const header = (label: string): string =>
  `// Generated by nifra from ${label}. Do not edit: \`nifra types\` rewrites it.`

function routeModule(
  name: string,
  extension: string,
  kind: "page" | "layout",
  hasBackend: boolean,
): string {
  // Only a script module's exports are visible to TypeScript; a .svelte/.vue one is an ambient shim.
  const script = extension === "tsx"
  const lines = [
    header(`routes/${name}.${extension}`),
    '/// <reference path="../../register.d.ts" />',
    '/// <reference path="../../routes.d.ts" />',
    'import type { OutputOf, RouteActionReturn, RouteLoaderArgs, RouteLoaderReturn, SearchSchemaOf } from "@nifrajs/client"',
  ]
  lines.push(
    kind === "page"
      ? 'import type { BoundaryLoadersOf, MetaArgs as WebMetaArgs, RenderProps } from "@nifrajs/web"'
      : 'import type { MetaArgs as WebMetaArgs } from "@nifrajs/web"',
  )
  lines.push("")
  if (hasBackend) lines.push(`type Backend = typeof import("../../../../routes/${name}.backend")`)
  if (script) lines.push(`type Frontend = typeof import("../../../../routes/${name}")`)
  if (hasBackend || script) lines.push("")
  const output = (schema: string): string =>
    hasBackend ? `OutputOf<Backend, "${schema}">` : "null"
  lines.push(
    "export namespace Route {",
    "  /** The URL params this route's path carries. */",
    "  export type Params = Record<string, never>",
    "  /** What the loader sends to the browser: the output type of `loaderOutput`. */",
    `  export type LoaderData = ${output("loaderOutput")}`,
    "  /** What the action sends back: the output type of `actionOutput`. */",
    `  export type ActionData = ${output("actionOutput")}`,
    "  /** The context the backend half's loader receives. */",
    `  export type LoaderArgs = RouteLoaderArgs<Params${script ? ", SearchSchemaOf<Frontend>" : ""}>`,
    "  /** The context the backend half's action receives. */",
    "  export type ActionArgs = LoaderArgs",
    "  /** The backend half's loader. Annotate it, `export const loader: Route.Loader = ...`, and what it returns is checked against `loaderOutput`. */",
    `  export type Loader = (args: LoaderArgs) => RouteLoaderReturn<${hasBackend ? "Backend" : "null"}>`,
    "  /** The backend half's action. Annotate it, `export const action: Route.Action = ...`, and what it returns is checked against `actionOutput`. */",
    `  export type Action = (args: ActionArgs) => RouteActionReturn<${hasBackend ? "Backend" : "null"}>`,
    "  /** What this module's `meta` function receives: its own loader data as `data`. */",
    "  export type MetaArgs = WebMetaArgs<LoaderData>",
  )
  if (kind === "page") {
    lines.push(
      "  /** The page component's props. */",
      '  export type ComponentProps = Omit<RenderProps, "data" | "actionData" | "params"> & {',
      "    readonly data: LoaderData",
      "    readonly actionData?: ActionData",
      "    readonly params: Params",
      "  }",
      "  /** The backend half's `boundaryLoaders`. Check it, `export const boundaryLoaders = { ... } satisfies Route.BoundaryLoaders`, and a key must name a boundary the page declares; with a `shellLoader`, every hole needs one. */",
      `  export type BoundaryLoaders = BoundaryLoadersOf<${script ? "Frontend" : "unknown"}, ${hasBackend ? "Backend" : "unknown"}>`,
    )
  } else {
    lines.push(
      "  /** The layout component's props; `Children` is the adapter's children type. */",
      "  export type ComponentProps<Children = unknown> = {",
      "    readonly data: LoaderData",
      "    readonly children?: Children",
      "  }",
    )
  }
  lines.push("}", "")
  return lines.join("\n")
}

/** `routes.d.ts` for the starter's one URL pattern, `/`, served by `routes/index`. */
function routeTable(extension: string): string {
  // Only a script module's exports are visible to TypeScript; a .svelte/.vue one is an ambient shim.
  const search =
    extension === "tsx"
      ? 'SearchOf<typeof import("../../routes/index")>'
      : "Record<string, unknown>"
  const slots =
    extension === "tsx"
      ? 'RouteSlotPatternsOf<typeof import("../../routes/index")>'
      : "Readonly<Record<never, never>>"
  return [
    header("routes/"),
    'import type { RouteSlotPatternsOf, SearchOf } from "@nifrajs/web"',
    "",
    'declare module "@nifrajs/web" {',
    "  interface RouteTable {",
    `    "/": { readonly params: Record<string, never>; readonly search: ${search}; readonly slots: ${slots} }`,
    "  }",
    "}",
    "",
  ].join("\n")
}

/** Every `.nifra/types` file of a starter whose route files carry `extension`, by app-relative path. */
export function starterRouteTypes(extension: string): Map<string, string> {
  const files = new Map<string, string>()
  files.set(
    ".nifra/types/register.d.ts",
    [
      header("backend/app.ts"),
      'import type { backend } from "../../backend/app"',
      "",
      'declare module "@nifrajs/client" {',
      "  interface Register {",
      "    readonly backend: typeof backend",
      "  }",
      "}",
      "",
    ].join("\n"),
  )
  files.set(".nifra/types/routes.d.ts", routeTable(extension))
  for (const [name, kind, hasBackend] of STARTER_ROUTES) {
    files.set(
      `.nifra/types/routes/+types/${name}.d.ts`,
      routeModule(name, extension, kind, hasBackend),
    )
  }
  return files
}
