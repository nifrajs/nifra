import { describe, expect, test } from "bun:test"
import {
  compileComponentModule,
  exportedValues,
  guardCreateElementCalls,
  sourceFile,
  staticComponentPipeline,
} from "../src/server-components/source.ts"

const file = "/fixture/backend/Summary.component.server.ts"
const compile = (source: string, environment = "ssr") =>
  compileComponentModule(source, file, "/fixture", environment)
const importNamed =
  'import { defineServerComponent as define } from "@nifrajs/web/server-components";'

describe("static component pipeline", () => {
  test("reads a wrapped literal and refuses anything that is not plain data", () => {
    expect(
      staticComponentPipeline(
        'export const componentPipeline = ({ "vue": { mode: "native" } } satisfies object) as const',
        "/fixture/nifra.config.ts",
      ),
    ).toEqual({ vue: { mode: "native" } })
    for (const initializer of [
      "{ mode }",
      '{ mode: "a", mode: "b" }',
      '{ constructor: "x" }',
      "{ mode: 1 }",
    ])
      expect(
        staticComponentPipeline(
          `export const componentPipeline = ${initializer}`,
          "/fixture/nifra.config.ts",
        ),
      ).toBeUndefined()
  })
})

describe("exported values of a native client module", () => {
  const exports = (source: string) => exportedValues(sourceFile(source, "/fixture/Page.ts"))

  test("lists every exported value name and skips type-only exports", () => {
    expect(
      exports(
        [
          'export type { Props } from "./props"',
          "const a = 1",
          "type B = string",
          "export { a, type B }",
          "export function load() {}",
          "export class Store {}",
          "export enum Mode { A }",
          "export default 1",
        ].join("\n"),
      ),
    ).toEqual(["a", "load", "Store", "Mode", "default"])
  })

  test("refuses a star re-export and a destructured export", () => {
    expect(() => exports('export * from "./other"')).toThrow(
      "Native client modules require explicit, schema-registered component exports",
    )
    expect(() => exports("export const { a } = { a: 1 }")).toThrow(
      "Destructured component exports are unsupported",
    )
  })
})

describe("component module compilation", () => {
  test("a use-server module is refused", () => {
    expect(() => compile(`"use server"\n${importNamed} export const S = define({})`)).toThrow(
      "Native use-server actions are unsupported",
    )
  })

  test("a namespace import and a wrapped definition both register", () => {
    const compiled = compile(
      'import * as sc from "@nifrajs/web/server-components"; export const Summary = (sc.defineServerComponent({ view() {} }) as never)',
    )
    expect(Object.keys(compiled.references)).toEqual(["Summary"])
    expect(compiled.code).toContain(`{ view() {} }, ${JSON.stringify(compiled.references.Summary)}`)
  })

  test("a named re-export of a local definition registers under its public name", () => {
    const compiled = compile(
      `${importNamed} const Local = define({}); type Shape = {}; export { Local as Summary, type Shape }`,
      "client",
    )
    expect(Object.keys(compiled.references)).toEqual(["Summary"])
    expect(compiled.code).toBe(
      `export const Summary = Object.freeze({ reference: ${JSON.stringify(compiled.references.Summary)} });`,
    )
  })

  test("refuses a handwritten reference, an unregistered export, and a module with none", () => {
    expect(() => compile(`${importNamed} export const S = define({}, "ref")`)).toThrow(
      "Component references are generated by the compiler",
    )
    expect(() =>
      compile(`${importNamed} const S = define({}); const other = 1; export { other }`),
    ).toThrow("A component module exported an unregistered value")
    expect(() => compile(`${importNamed} export type Only = string`)).toThrow(
      "A component module has no recognized server component",
    )
  })
})

describe("createElement guard", () => {
  test("a computed createElement call on the default import is guarded", () => {
    const guarded = guardCreateElementCalls(
      'import React from "react"\nexport const el = React["createElement"]("div")',
      "/fixture/Page.tsx",
    )
    expect(guarded).not.toContain('React["createElement"]')
    expect(guarded).toMatch(/__nifra_guardedCreateElement_[0-9a-f]{12}\("div"\)/)
  })
})
