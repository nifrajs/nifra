#!/usr/bin/env bun
/**
 * Generate every cross-package copy from its one source.
 *
 * Some packages carry a module another package owns, because they have no runtime dependency on the
 * owner by design (`node`, `proxy` and `image` depend on no `@nifrajs` package; `cli` must not depend
 * on `create-nifra`). Each copy here is its source verbatim under a header naming that source, or,
 * with `symbols`, only the named top-level declarations. `--check` refuses a copy that differs from
 * what this writes, so a hand edit to a copy, or a source edit nobody regenerated, fails CI instead
 * of drifting.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import ts from "typescript"

const ROOT = resolve(import.meta.dir, "..")
const HEADER = "// Generated by scripts/gen-vendored.ts - edit "

export interface VendoredCopy {
  /** The one file to edit. */
  readonly source: string
  readonly targets: readonly string[]
  /** Top-level declarations to copy instead of the whole file. */
  readonly symbols?: readonly string[]
  /** The header's second line: why the target carries a copy instead of importing the source. */
  readonly why: string
}

