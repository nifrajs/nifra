function parse(root: string, path: string): ts.SourceFile {
  return ts.createSourceFile(
    path,
    readFileSync(resolve(root, path), "utf8"),
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  )
}

/** A relative specifier resolves against the target's directory and a package one needs a dependency
 * the target does not declare; a `node:` builtin resolves wherever the source already runs. */
function refuseImports(file: ts.SourceFile, source: string): void {
  for (const statement of file.statements) {
    if (!ts.isImportDeclaration(statement) && !ts.isExportDeclaration(statement)) continue
    const specifier = statement.moduleSpecifier
    if (specifier === undefined || !ts.isStringLiteral(specifier)) continue
    if (!specifier.text.startsWith("node:"))
      throw new Error(
        `${source} imports "${specifier.text}" - a vendored copy may import only node: builtins`,
      )
  }
}

function declarationText(file: ts.SourceFile, source: string, name: string): string {
  const declaration = file.statements.find((statement) =>
    ts.isVariableStatement(statement)
      ? statement.declarationList.declarations.some(
          (decl) => ts.isIdentifier(decl.name) && decl.name.text === name,
        )
      : (ts.isTypeAliasDeclaration(statement) ||
          ts.isInterfaceDeclaration(statement) ||
          ts.isFunctionDeclaration(statement)) &&
        statement.name?.text === name,
  )
  if (declaration === undefined) throw new Error(`${name} missing from ${source}`)
  return `${declaration.getText(file)}\n`
}

/** The exact text every target of `copy` holds. */
export function renderCopy(root: string, copy: VendoredCopy): string {
  const file = parse(root, copy.source)
  let body: string
  if (copy.symbols === undefined) {
    refuseImports(file, copy.source)
    body = file.getFullText()
  } else {
    body = copy.symbols.map((name) => declarationText(file, copy.source, name)).join("\n")
  }
  return [`${HEADER}${copy.source} instead.`, `// ${copy.why}`, "", body].join("\n")
}

export interface StaleCopy {
  readonly target: string
  readonly source: string
}

/** The targets under `root` whose content differs from what this generator writes. */
export function staleCopies(
  root: string = ROOT,
  manifest: readonly VendoredCopy[] = VENDORED,
): StaleCopy[] {
  const stale: StaleCopy[] = []
  for (const copy of manifest) {
    const expected = renderCopy(root, copy)
    for (const target of copy.targets) {
      const path = resolve(root, target)
      if ((existsSync(path) ? readFileSync(path, "utf8") : "") !== expected)
        stale.push({ target, source: copy.source })
    }
  }
  return stale
}

/** Files under `packages/` that carry this generator's header but are no manifest target, such as a
 * copy whose entry was removed: nothing regenerates or checks it, so it would drift unseen. */
export function orphanCopies(
  root: string = ROOT,
  manifest: readonly VendoredCopy[] = VENDORED,
): string[] {
  const targets = new Set(manifest.flatMap((copy) => copy.targets))
  const orphans: string[] = []
  for (const path of new Bun.Glob("packages/*/src/**/*.ts").scanSync({ cwd: root })) {
    if (targets.has(path)) continue
    if (readFileSync(resolve(root, path), "utf8").startsWith(HEADER)) orphans.push(path)
  }
  return orphans.sort()
}

/** Rewrite every stale target; returns the ones written. */
export function writeCopies(
  root: string = ROOT,
  manifest: readonly VendoredCopy[] = VENDORED,
): string[] {
  const stale = staleCopies(root, manifest)
  for (const { target, source } of stale) {
    const copy = manifest.find((entry) => entry.source === source)
    if (copy === undefined) continue
    const path = resolve(root, target)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, renderCopy(root, copy))
  }
  return stale.map(({ target }) => target)
}

if (import.meta.main) {
  const orphans = orphanCopies()
  for (const path of orphans)
    console.error(
      `✗ ${path} has a generated header but no entry in scripts/gen-vendored.ts - add it or remove the header.`,
    )
  if (process.argv.includes("--check")) {
    const stale = staleCopies()
    for (const { target, source } of stale)
      console.error(
        `✗ ${target} is not what ${source} generates - edit the source, never the copy, then run \`bun run gen:vendored\`.`,
      )
    if (stale.length > 0 || orphans.length > 0) process.exit(1)
    const count = VENDORED.reduce((sum, copy) => sum + copy.targets.length, 0)
    console.log(`✓ ${count} vendored copies match their sources`)
  } else {
    const written = writeCopies()
    for (const target of written) console.log(`wrote ${target}`)
    if (orphans.length > 0) process.exit(1)
    if (written.length === 0) console.log("✓ every vendored copy was current")
  }
}
