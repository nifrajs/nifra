#!/usr/bin/env bun
/**
 * Generate the type-only Node outcome contract consumed by @nifrajs/node.
 *
 * The Node adapter deliberately has no runtime dependency on @nifrajs/core. Keeping the outcome
 * contract generated from core preserves that deployment shape while making drift visible to the
 * adapter's own TypeScript build and to a checked-in --check gate.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import ts from "typescript"
import { runNodeOutcomeConformance } from "./node-outcome-conformance.ts"

const ROOT = resolve(import.meta.dir, "..")
const OUTCOME_SOURCE = "packages/core/src/server/node-outcome.ts"
const OUTCOME_TARGET = "packages/node/src/generated/node-outcome.ts"
const MARKERS_SOURCE = "packages/core/src/server/bridge-markers.ts"
const MARKERS_TARGET = "packages/node/src/generated/bridge-markers.ts"
const TARGET_SOURCE = "packages/core/src/server/request-target.ts"
const TARGET_TARGET = "packages/node/src/generated/request-target.ts"
const STATIC_FILE_SOURCE = "packages/core/src/static-file.ts"
const STATIC_FILE_TARGET = "packages/node/src/generated/static-file.ts"

function parse(sourcePath: string): ts.SourceFile {
  return ts.createSourceFile(
    sourcePath,
    readFileSync(sourcePath, "utf8"),
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  )
}

export function generateNodeOutcomeContract(root: string = ROOT): string {
  const source = parse(resolve(root, OUTCOME_SOURCE))
  const declaration = source.statements.find(
    (statement): statement is ts.TypeAliasDeclaration =>
      ts.isTypeAliasDeclaration(statement) && statement.name.text === "NodeServeOutcome",
  )
  if (declaration === undefined) {
    throw new Error(`node outcome contract missing from ${OUTCOME_SOURCE}`)
  }
  return [
    "// Generated by scripts/gen-node-outcome.ts - edit packages/core/src/server/node-outcome.ts instead.",
    "// This file is type-only so @nifrajs/node stays free of a runtime @nifrajs/core dependency.",
    "",
    `${declaration.getText(source)}\n`,
  ].join("\n")
}

/**
 * The wire marker keys, copied verbatim from core's single source. A runtime const rather than a type
 * (the strings ARE the protocol), but still no runtime dependency on core: the literals are inlined at
 * generation time exactly as the outcome type is.
 */
export function generateBridgeMarkers(root: string = ROOT): string {
  const source = parse(resolve(root, MARKERS_SOURCE))
  const declaration = source.statements.find(
    (statement): statement is ts.VariableStatement =>
      ts.isVariableStatement(statement) &&
      statement.declarationList.declarations.some(
        (decl) => ts.isIdentifier(decl.name) && decl.name.text === "NODE_BRIDGE_MARKER_KEYS",
      ),
  )
  if (declaration === undefined) {
    throw new Error(`NODE_BRIDGE_MARKER_KEYS missing from ${MARKERS_SOURCE}`)
  }
  return [
    "// Generated by scripts/gen-node-outcome.ts - edit packages/core/src/server/bridge-markers.ts instead.",
    "// The marker strings ARE the wire protocol; copied here so @nifrajs/node reads the identical keys",
    "// without a runtime dependency on @nifrajs/core.",
    "",
    `${declaration.getText(source)}\n`,
  ].join("\n")
}

/**
 * The request-target resolver, copied whole: Node's `IncomingMessage.url` is the raw target, so the
 * adapter resolves it with the exact function core applies to a raw `Request` URL. The module must
 * stay import-free for the copy to run without core.
 */
export function generateRequestTarget(root: string = ROOT): string {
  const source = parse(resolve(root, TARGET_SOURCE))
  if (source.statements.some((statement) => ts.isImportDeclaration(statement))) {
    throw new Error(`${TARGET_SOURCE} must not import anything - @nifrajs/node runs a copy of it`)
  }
  return [
    "// Generated by scripts/gen-node-outcome.ts - edit packages/core/src/server/request-target.ts instead.",
    "// Copied so @nifrajs/node resolves a raw target exactly as core does, without depending on it.",
    "",
    source.getFullText(),
  ].join("\n")
}

/** The static-file policy (media types, hidden paths), copied whole so the adapter's `static` reader
 * types and hides files exactly as web does. */
export function generateStaticFile(root: string = ROOT): string {
  const source = parse(resolve(root, STATIC_FILE_SOURCE))
  if (source.statements.some((statement) => ts.isImportDeclaration(statement))) {
    throw new Error(
      `${STATIC_FILE_SOURCE} must not import anything - @nifrajs/node runs a copy of it`,
    )
  }
  return [
    "// Generated by scripts/gen-node-outcome.ts - edit packages/core/src/static-file.ts instead.",
    "// Copied so @nifrajs/node types and hides served files exactly as core does, without depending on it.",
    "",
    source.getFullText(),
  ].join("\n")
}

const ARTIFACTS: readonly { readonly target: string; readonly render: (root: string) => string }[] =
  [
    { target: OUTCOME_TARGET, render: generateNodeOutcomeContract },
    { target: MARKERS_TARGET, render: generateBridgeMarkers },
    { target: TARGET_TARGET, render: generateRequestTarget },
    { target: STATIC_FILE_TARGET, render: generateStaticFile },
  ]

/** The generated files under `root` whose content differs from what this generator writes. */
export function staleArtifacts(root: string = ROOT): string[] {
  return ARTIFACTS.filter(({ target, render }) => {
    const path = resolve(root, target)
    return (existsSync(path) ? readFileSync(path, "utf8") : "") !== render(root)
  }).map(({ target }) => target)
}

if (import.meta.main) {
  const check = process.argv.includes("--check")
  if (check) {
    const stale = staleArtifacts()
    for (const target of stale)
      console.error(`✗ ${target} is stale - run \`bun run gen:node-outcome\`.`)
    if (stale.length > 0) process.exit(1)
  } else {
    for (const { target, render } of ARTIFACTS) {
      const path = resolve(ROOT, target)
      mkdirSync(resolve(path, ".."), { recursive: true })
      writeFileSync(path, render(ROOT))
    }
  }
  if (check) {
    await runNodeOutcomeConformance()
    console.log("✓ @nifrajs/node outcome contract is current")
  } else {
    console.log(
      "Generated @nifrajs/node outcome contract, bridge markers, request-target resolver + static-file policy.",
    )
  }
}
