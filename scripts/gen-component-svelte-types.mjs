import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { tmpdir } from "node:os"
import { resolve } from "node:path"

const root = resolve(import.meta.dirname, "../packages/web-svelte")
const require = createRequire(resolve(root, "package.json"))
const { emitDts } = require("svelte2tsx")
const stage = await mkdtemp(resolve(tmpdir(), "nifra-svelte-types-"))
try {
  await emitDts({
    declarationDir: stage,
    libRoot: resolve(root, "src/server-components"),
    tsconfig: resolve(root, "tsconfig.components.json"),
    svelteShimsPath: require.resolve("svelte2tsx/svelte-shims-v4.d.ts"),
  })
  const output =
    "// Generated by scripts/gen-component-svelte-types.mjs from ServerComponent.svelte.\n" +
    (await readFile(resolve(stage, "ServerComponent.svelte.d.ts"), "utf8"))
  const target = resolve(root, "src/server-components/ServerComponent.svelte.d.ts")
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== output)
      throw new Error("ServerComponent.svelte declarations are stale; run the Svelte adapter build")
  } else await writeFile(target, output)
} finally {
  await rm(stage, { recursive: true, force: true })
}
