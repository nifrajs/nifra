import { afterEach, expect, test } from "bun:test"
import {
  appendFileSync,
  cpSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import {
  orphanCopies,
  readText,
  renderCopy,
  staleCopies,
  VENDORED,
  type VendoredCopy,
  writeCopies,
} from "./gen-vendored.ts"

const ROOT = join(import.meta.dir, "..")
const roots: string[] = []

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true })
})

function fixture(): string {
  const root = mkdtempSync(join(tmpdir(), "vendored-"))
  roots.push(root)
  for (const copy of VENDORED)
    for (const file of [copy.source, ...copy.targets]) cpSync(join(ROOT, file), join(root, file))
  return root
}

function write(root: string, path: string, text: string): void {
  mkdirSync(dirname(join(root, path)), { recursive: true })
  writeFileSync(join(root, path), text)
}

const targetsOf = (root: string): string[] => staleCopies(root).map(({ target }) => target)

test("control: the committed copies are current and none is orphaned", () => {
  const root = fixture()
  expect({ stale: staleCopies(root), orphans: orphanCopies(root) }).toEqual({
    stale: [],
    orphans: [],
  })
})

test("a CRLF checkout of the committed copies and sources is current", () => {
  const root = fixture()
  for (const copy of VENDORED)
    for (const file of [copy.source, ...copy.targets]) {
      const path = join(root, file)
      writeFileSync(path, readText(path).replaceAll("\n", "\r\n"))
    }
  expect({ stale: staleCopies(root), orphans: orphanCopies(root) }).toEqual({
    stale: [],
    orphans: [],
  })
})

test("every whole-file copy is its source byte for byte under the header", () => {
  for (const copy of VENDORED.filter((entry) => entry.symbols === undefined)) {
    const source = readText(join(ROOT, copy.source))
    for (const target of copy.targets) {
      const lines = readText(join(ROOT, target)).split("\n")
      expect({ target, header: lines[0], body: lines.slice(3).join("\n") }).toEqual({
        target,
        header: `// Generated by scripts/gen-vendored.ts - edit ${copy.source} instead.`,
        body: source,
      })
    }
  }
})

test("a hand edit to any copy is refused, naming the copy and its source", () => {
  for (const copy of VENDORED) {
    for (const target of copy.targets) {
      const root = fixture()
      appendFileSync(join(root, target), "// hand edit\n")
      expect(staleCopies(root)).toEqual([{ target, source: copy.source }])
    }
  }
})

test("a source edit nobody regenerated leaves every target of it stale", () => {
  for (const copy of VENDORED) {
    const root = fixture()
    const path = join(root, copy.source)
    const text = readFileSync(path, "utf8")
    // A symbol copy carries only its declarations, so the edit lands inside the first one.
    const symbol = copy.symbols?.[0]
    const edited =
      symbol === undefined
        ? `${text}\n// drift\n`
        : text.replace(
            new RegExp(`\\b(?:const|type|interface|function) ${symbol}\\b`),
            "$& /* drift */",
          )
    expect(edited).not.toBe(text)
    writeFileSync(path, edited)
    expect({ source: copy.source, stale: targetsOf(root) }).toEqual({
      source: copy.source,
      stale: [...copy.targets],
    })
  }
})

test("a symbol copy ignores source text outside its declarations", () => {
  const root = fixture()
  for (const copy of VENDORED.filter((entry) => entry.symbols !== undefined))
    appendFileSync(join(root, copy.source), "\nexport const unrelated = 1\n")
  expect(staleCopies(root)).toEqual([])
})

test("a missing copy is stale, and writing restores every stale copy", () => {
  const root = fixture()
  const [first, second] = VENDORED.flatMap((copy) => copy.targets)
  if (first === undefined || second === undefined) throw new Error("manifest has under two targets")
  rmSync(join(root, first))
  appendFileSync(join(root, second), "// hand edit\n")
  expect(targetsOf(root)).toEqual([first, second])
  expect(writeCopies(root)).toEqual([first, second])
  expect(staleCopies(root)).toEqual([])
  expect(writeCopies(root)).toEqual([])
})

test("a whole-file source may import only node: builtins", () => {
  const root = mkdtempSync(join(tmpdir(), "vendored-"))
  roots.push(root)
  const copy: VendoredCopy = { source: "packages/a/src/m.ts", targets: [], why: "test" }
  write(root, copy.source, 'import { readFile } from "node:fs/promises"\nexport { readFile }\n')
  expect(renderCopy(root, copy)).toEndWith(
    'import { readFile } from "node:fs/promises"\nexport { readFile }\n',
  )
  for (const [line, specifier] of [
    ['import { x } from "./x.ts"', "./x.ts"],
    ['import type { Server } from "@nifrajs/core"', "@nifrajs/core"],
    ['export * from "../shared.ts"', "../shared.ts"],
  ]) {
    write(root, copy.source, `${line}\n`)
    expect(() => renderCopy(root, copy)).toThrow(
      `packages/a/src/m.ts imports "${specifier}" - a vendored copy may import only node: builtins`,
    )
  }
})

test("a symbol missing from its source is refused, not copied empty", () => {
  const root = mkdtempSync(join(tmpdir(), "vendored-"))
  roots.push(root)
  const copy: VendoredCopy = {
    source: "packages/a/src/m.ts",
    targets: [],
    symbols: ["Shape", "LIMIT", "Gone"],
    why: "test",
  }
  write(
    root,
    copy.source,
    'import { x } from "./x.ts"\nexport type Shape = { a: 1 }\nexport const LIMIT = x\n',
  )
  expect(() => renderCopy(root, copy)).toThrow("Gone missing from packages/a/src/m.ts")
  expect(renderCopy(root, { ...copy, symbols: ["Shape", "LIMIT"] })).toBe(
    [
      "// Generated by scripts/gen-vendored.ts - edit packages/a/src/m.ts instead.",
      "// test",
      "",
      "export type Shape = { a: 1 }\n\nexport const LIMIT = x\n",
    ].join("\n"),
  )
})

test("a generated file with no manifest entry is an orphan", () => {
  const root = fixture()
  const [copy] = VENDORED
  if (copy === undefined) throw new Error("empty manifest")
  write(root, "packages/deno/src/kept.ts", renderCopy(root, copy))
  write(root, "packages/deno/src/own.ts", "export const own = 1\n")
  expect(orphanCopies(root)).toEqual(["packages/deno/src/kept.ts"])
  expect(
    orphanCopies(root, [...VENDORED, { ...copy, targets: ["packages/deno/src/kept.ts"] }]),
  ).toEqual([])
})
